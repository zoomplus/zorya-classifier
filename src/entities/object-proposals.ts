import type { PixelRect } from './contracts.js'
import type { RgbaRaster } from './representation.js'
import type { SegmentationMetadata } from './segmentation-metadata.js'

/** One-shot packed proposals avoid keeping native workers alive during model requests. */
export const objectProposalLimits = Object.freeze({
  imagePixels: 2_097_152,
  candidates: 36,
  packedBytes: 10 * 1024 * 1024,
  presentationBytes: 16 * 1024 * 1024,
  presentationImages: 4,
})

/** Row-major, least-significant bit first; unused bits in the last byte must be zero. */
export interface PackedBinaryMask {
  data: Uint8Array
  width: number
  height: number
  format: 'binary-lsb0'
}

export interface ObjectProposal {
  /** Stable input-order alias C00…C35, never a case ID or semantic annotation. */
  id: string
  mask: PackedBinaryMask
  /** Uncalibrated native diagnostic only; never included in model requests. */
  qualityScore?: number
}

export interface ObjectProposalInput {
  image: RgbaRaster
  seedRegion: PixelRect
  roi: PixelRect
  signal: AbortSignal
}

export interface ObjectProposalBatch {
  proposals: readonly ObjectProposal[]
  metadata: SegmentationMetadata
}

/**
 * Caller-owned. propose settles only after physical work closes; no model calls here.
 * @experimental Mask proposal strategy with no general quality qualification.
 */
export interface ObjectProposalPort {
  propose(input: ObjectProposalInput): Promise<ObjectProposalBatch>
  settle(): Promise<void>
  dispose(): Promise<void>
}

/** Pixel-derived boxes are computed and validated by the process, never generated by a model. */
export interface PresentedObjectProposal extends ObjectProposal {
  region: PixelRect | null
}

export interface ObjectProposalPresentationPort {
  render(input: {
    image: RgbaRaster
    seedRegion: PixelRect
    proposals: readonly PresentedObjectProposal[]
    signal: AbortSignal
  }): Promise<readonly Uint8Array[]>
}
